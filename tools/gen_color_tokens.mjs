#!/usr/bin/env node
// Generates src/tokens/baseline.rs from the Jetpack Compose material3 token
// files (androidx-main, compose/material3/material3/src/commonMain/kotlin/
// androidx/compose/material3/tokens): ColorLightTokens.kt,
// ColorDarkTokens.kt and PaletteTokens.kt.
//
// Usage: node tools/gen_color_tokens.mjs <dir-with-kt-files> > src/tokens/baseline.rs
import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: gen_color_tokens.mjs <kt-dir>");
  process.exit(2);
}

// `inline val Name: ...` followed by `get() = value` on the next line.
function getters(file) {
  const text = readFileSync(join(dir, file), "utf8");
  const out = new Map();
  const re = /val\s+(\w+)\s*:[^\n]*\n\s*get\(\)\s*=\s*([^\n]+)/g;
  for (const m of text.matchAll(re)) out.set(m[1], m[2].trim());
  return out;
}

const palette = new Map();
for (const [k, v] of getters("PaletteTokens.kt")) {
  const m = v.match(/Color\(0xFF([0-9A-Fa-f]{6})\)/);
  if (m) palette.set(k, m[1].toUpperCase());
}

function resolve(scheme, name, seen = new Set()) {
  const v = scheme.get(name);
  if (v === undefined) return undefined;
  const p = v.match(/^PaletteTokens\.(\w+)$/);
  if (p) return palette.get(p[1]);
  if (/^\w+$/.test(v) && !seen.has(v)) return resolve(scheme, v, seen.add(name));
  return undefined;
}

// ColorRole variants in declaration order (src/tokens/color.rs).
const roles = [
  "Primary", "SurfaceTint", "OnPrimary", "PrimaryContainer", "OnPrimaryContainer",
  "Secondary", "OnSecondary", "SecondaryContainer", "OnSecondaryContainer",
  "Tertiary", "OnTertiary", "TertiaryContainer", "OnTertiaryContainer",
  "Error", "OnError", "ErrorContainer", "OnErrorContainer",
  "Background", "OnBackground", "Surface", "OnSurface", "SurfaceVariant",
  "OnSurfaceVariant", "Outline", "OutlineVariant", "Shadow", "Scrim",
  "InverseSurface", "InverseOnSurface", "InversePrimary",
  "PrimaryFixed", "OnPrimaryFixed", "PrimaryFixedDim", "OnPrimaryFixedVariant",
  "SecondaryFixed", "OnSecondaryFixed", "SecondaryFixedDim", "OnSecondaryFixedVariant",
  "TertiaryFixed", "OnTertiaryFixed", "TertiaryFixedDim", "OnTertiaryFixedVariant",
  "SurfaceDim", "SurfaceBright", "SurfaceContainerLowest", "SurfaceContainerLow",
  "SurfaceContainer", "SurfaceContainerHigh", "SurfaceContainerHighest",
];

function table(file) {
  const scheme = getters(file);
  return roles.map((r) => {
    // Compose's ColorScheme has no shadow role: Material renders shadows in
    // black (PaletteTokens.Neutral0), so that is what Shadow resolves to.
    const hex = r === "Shadow" ? palette.get("Neutral0") : resolve(scheme, r);
    if (!hex) throw new Error(`${file}: cannot resolve ${r}`);
    return `    0x${hex}, // ${r}`;
  }).join("\n");
}

console.log(`//! Baseline colour schemes, generated by \`tools/gen_color_tokens.mjs\`
//! from Compose's \`ColorLightTokens.kt\`, \`ColorDarkTokens.kt\` and
//! \`PaletteTokens.kt\`. Do not edit by hand. Entries follow
//! [\`ColorRole::ALL\`](super::ColorRole::ALL) order, as \`0xRRGGBB\`.

/// \`ColorLightTokens\`, one entry per role.
pub(crate) const LIGHT: [u32; ${roles.length}] = [
${table("ColorLightTokens.kt")}
];

/// \`ColorDarkTokens\`, one entry per role.
pub(crate) const DARK: [u32; ${roles.length}] = [
${table("ColorDarkTokens.kt")}
];`);
