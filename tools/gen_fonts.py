#!/usr/bin/env python3
r"""Cut the bundled fonts and generate the Material Symbols codepoint table.

egui-material3 bundles static font instances under resources/fonts/ and a
name -> codepoint table in src/material_symbol/codepoints.rs. Both are
produced by this script from upstream variable fonts, so they can be
regenerated when Google updates the fonts:

  Roboto[wdth,wght].ttf          https://github.com/google/fonts/tree/main/ofl/roboto
  MaterialSymbols<Style>[FILL,GRAD,opsz,wght].ttf
                                 https://github.com/google/material-design-icons/tree/master/variablefont

Usage (from the repository root, fontTools >= 4.40 installed):

  python tools/gen_fonts.py --roboto Roboto.ttf \
      --outlined MaterialSymbolsOutlined.ttf \
      --codepoints MaterialSymbolsOutlined.codepoints \
      --rounded MaterialSymbolsRounded.ttf \
      --sharp MaterialSymbolsSharp.ttf

Each input is optional; only the outputs for the given inputs are written.
The codepoint table is generated from --outlined, with the names in
--codepoints (the `.codepoints` file next to the variable font upstream).

Outputs:
  resources/fonts/Roboto-{Regular,Medium,Bold}.ttf
      wght 400/500/700 at wdth 100, all layout features kept (kerning).
  resources/fonts/MaterialSymbols<Style>-Fill{0,1}.ttf
      FILL 0/1, wght 400, GRAD 0, opsz 24, subset to the private-use icon
      codepoints with no layout tables (egui looks icons up by codepoint,
      so the ligature table is dead weight). --weights 300,500,700 also
      writes -Fill{0,1}-W<weight> files for apps that bundle more weights.
  src/material_symbol/codepoints.rs (from --outlined and --codepoints)
"""

import argparse
import io
import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "resources", "fonts")
CODEPOINTS = os.path.join(ROOT, "src", "material_symbol", "codepoints.rs")

ROBOTO_WEIGHTS = [(400, "Regular"), (500, "Medium"), (700, "Bold")]
PUA = [(0xE000, 0xF8FF), (0xF0000, 0x10FFFF)]


def is_pua(cp):
    return any(lo <= cp <= hi for lo, hi in PUA)


def instance(path, axes):
    font = TTFont(path)
    return instancer.instantiateVariableFont(font, axes, updateFontNames=False)


def save(font, name):
    os.makedirs(FONTS, exist_ok=True)
    out = os.path.join(FONTS, name)
    font.save(out)
    print(f"{out}: {os.path.getsize(out)} bytes")


def roboto(path):
    for weight, style in ROBOTO_WEIGHTS:
        save(instance(path, {"wght": weight, "wdth": 100}), f"Roboto-{style}.ttf")


def symbols(path, style, weights):
    for weight in weights:
        for fill in (0, 1):
            font = instance(path, {"FILL": fill, "wght": weight, "GRAD": 0, "opsz": 24})
            options = subset.Options()
            options.layout_features = []
            options.glyph_names = False
            options.notdef_outline = True
            options.name_IDs = ["*"]
            subsetter = subset.Subsetter(options)
            unicodes = [cp for cp in font.getBestCmap() if is_pua(cp)]
            subsetter.populate(unicodes=unicodes)
            subsetter.subset(font)
            for table in ("GSUB", "GPOS", "GDEF", "STAT"):
                if table in font:
                    del font[table]
            suffix = "" if weight == 400 else f"-W{weight}"
            save(font, f"MaterialSymbols{style}-Fill{fill}{suffix}.ttf")


def const_name(name):
    return "ICON_" + re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def codepoints(path, listing):
    font = TTFont(path, lazy=True)
    version = font["name"].getDebugName(5)
    cmap = font.getBestCmap()
    by_name = {}
    if listing:
        # Google's .codepoints file names every icon, aliases included
        # ("clear" and "close" share a glyph); keep the ones the font maps.
        with open(listing, encoding="utf-8") as f:
            for line in f:
                parts = line.split()
                if len(parts) == 2 and int(parts[1], 16) in cmap:
                    by_name.setdefault(parts[0], int(parts[1], 16))
    for cp, glyph in sorted(cmap.items()):
        if not is_pua(cp):
            continue
        name = glyph[1:] if glyph.startswith("_") else glyph
        if not re.fullmatch(r"[a-z0-9_]+", name):
            print(f"skipping glyph {glyph!r}", file=sys.stderr)
            continue
        by_name.setdefault(name, cp)  # lowest codepoint wins
    names = sorted(by_name)
    consts = {}
    for name in names:
        const = const_name(name)
        if const in consts:
            sys.exit(f"constant {const} for both {consts[const]!r} and {name!r}")
        consts[const] = name

    out = io.StringIO()
    out.write("//! Material Symbols codepoints, generated by `tools/gen_fonts.py` from\n")
    out.write(f"//! `MaterialSymbolsOutlined[FILL,GRAD,opsz,wght].ttf` ({version}).\n")
    out.write("//! Do not edit by hand.\n\n")
    for name in names:
        out.write(f"/// `{name}`\n")
        out.write(f"pub const {const_name(name)}: char = '\\u{{{by_name[name]:x}}}';\n")
    out.write("\n/// Every icon name with its codepoint, sorted by name.\n")
    out.write("pub static ICON_NAMES: &[(&str, char)] = &[\n")
    for name in names:
        out.write(f'    ("{name}", {const_name(name)}),\n')
    out.write("];\n")
    os.makedirs(os.path.dirname(CODEPOINTS), exist_ok=True)
    with open(CODEPOINTS, "w", encoding="utf-8", newline="\n") as f:
        f.write(out.getvalue())
    print(f"{CODEPOINTS}: {len(names)} icons")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--roboto")
    parser.add_argument("--outlined")
    parser.add_argument("--codepoints", help="the .codepoints file shipped with --outlined")
    parser.add_argument("--rounded")
    parser.add_argument("--sharp")
    parser.add_argument("--weights", default="400", help="comma-separated symbol weights")
    args = parser.parse_args()
    weights = [int(w) for w in args.weights.split(",")]

    if args.roboto:
        roboto(args.roboto)
    for style, path in (("Outlined", args.outlined), ("Rounded", args.rounded), ("Sharp", args.sharp)):
        if path:
            symbols(path, style, weights)
    if args.outlined:
        codepoints(args.outlined, args.codepoints)


if __name__ == "__main__":
    main()
